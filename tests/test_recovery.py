from control.active import load_active, reserve_attempt
from device.latch import DeviceSample
from device.recording import DeviceError
from tests import BATCH, BenchCase


class RecoveryTests(BenchCase):
    def test_pending_command_on_reopen(self):
        bench = self.open_bench(automatic=False)
        self.admit(bench)
        self.assertEqual(bench.advance(BATCH).status, 'pending')
        old = load_active(bench.db)
        bench.close()
        reopened = self.open_bench(automatic=False)
        self.assertEqual(reopened.device.read_latest(), DeviceSample(40, 12))
        self.assertEqual(reopened.resume(BATCH).status, 'pending')
        self.assertIsNone(reopened.device.terminal(old.session_id))
        self.assertEqual(load_active(reopened.db), old)
        self.assert_actions(reopened, [])
        with self.assertRaises(DeviceError):
            reopened.device.submit(old.session_id, 'after-seal', 'bottle-B')
        running = reopened.device.tick()
        self.assertEqual((running.command_id, running.state), (old.command_id, 'running'))
        self.assertEqual(reopened.resume(BATCH).status, 'pending')
        self.assert_actions(reopened, [('bottle-A', None)])
        completed = reopened.device.tick()
        self.assertEqual((completed.command_id, completed.completion_number), (old.command_id, 41))
        terminal = reopened.device.terminal(old.session_id)
        self.assertEqual(terminal.mode, 'seal')
        self.assertEqual(terminal.outcome_for(old.command_id), completed)
        result = reopened.resume(BATCH)
        self.assertEqual(result.status, 'published')
        self.assert_sample(result.sample, 'A', 'bottle-A', 41, 17, '53/8')
        self.assert_actions(reopened, [('bottle-A', 41)])
        reopened.device.automatic = True
        following = reopened.advance(BATCH)
        self.assert_sample(following.sample, 'B', 'bottle-B', 42, 23, '71/8')
        self.assert_actions(reopened, [('bottle-A', 41), ('bottle-B', 42)])

    def test_running_command_on_reopen(self):
        bench = self.open_bench(automatic=False)
        self.admit(bench)
        self.assertEqual(bench.advance(BATCH).status, 'pending')
        started = bench.device.tick()
        self.assertEqual(started.state, 'running')
        bench.close()
        recovered = self.open_bench()
        self.assertEqual(recovered.device.read_latest(), DeviceSample(40, 12))
        self.assertEqual(recovered.resume(BATCH).status, 'pending')
        self.assert_actions(recovered, [('bottle-A', None)])
        self.assertEqual(recovered.device.tick().command_id, started.command_id)
        result = recovered.resume(BATCH)
        self.assertEqual(result.status, 'published')
        self.assert_sample(result.sample, 'A', 'bottle-A', 41, 17, '53/8')
        self.assert_actions(recovered, [('bottle-A', 41)])

    def test_cancelled_then_resend(self):
        bench = self.open_bench(automatic=False)
        self.admit(bench)
        self.assertEqual(bench.advance(BATCH).status, 'pending')
        old = load_active(bench.db)
        bench.device.close(old.session_id)
        self.assertEqual(bench.device.read_latest(), DeviceSample(40, 12))
        terminal = bench.device.terminal(old.session_id)
        self.assertEqual(terminal.mode, 'close')
        self.assertEqual(terminal.outcome_for(old.command_id).state, 'cancelled')
        self.assertIsNone(bench.device.tick())
        bench.close()
        recovered = self.open_bench()
        self.assertEqual(recovered.device.read_latest(), DeviceSample(40, 12))
        result = recovered.resume(BATCH)
        self.assertEqual(result.status, 'published')
        self.assert_sample(result.sample, 'A', 'bottle-A', 41, 17, '53/8')
        self.assert_actions(recovered, [('bottle-A', 41)])
        self.assertNotEqual(recovered.device.recording.read_actions()[0].command_id, old.command_id)
        self.assertEqual(recovered.device.terminal(old.session_id), terminal)

    def test_close_waits_for_running_action(self):
        bench = self.open_bench(automatic=False)
        self.admit(bench)
        bench.advance(BATCH)
        started = bench.device.tick()
        bench.device.close(started.session_id)
        self.assertIsNone(bench.device.terminal(started.session_id))
        bench.close()
        recovered = self.open_bench()
        self.assertEqual(recovered.resume(BATCH).status, 'pending')
        self.assert_actions(recovered, [('bottle-A', None)])
        recovered.device.tick()
        terminal = recovered.device.terminal(started.session_id)
        self.assertEqual(terminal.mode, 'close')
        self.assertEqual(terminal.outcome_for(started.command_id).completion_number, 41)
        self.assert_sample(recovered.resume(BATCH).sample, 'A', 'bottle-A', 41, 17, '53/8')
        self.assert_actions(recovered, [('bottle-A', 41)])

    def test_reserved_command_never_reached_device(self):
        bench = self.open_bench(automatic=False)
        first, _ = self.admit(bench)
        session = bench.device.open_session()
        attempt = reserve_attempt(bench.db, first.job, session, 'before-dispatch')
        self.assertIsNotNone(attempt)
        bench.close()
        recovered = self.open_bench()
        self.assert_sample(recovered.resume(BATCH).sample, 'A', 'bottle-A', 41, 17, '53/8')
        self.assertEqual(recovered.device.terminal(session).outcomes, ())
        self.assert_actions(recovered, [('bottle-A', 41)])
